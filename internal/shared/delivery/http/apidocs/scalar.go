package apidocs

import (
	"net/http"

	"github.com/gin-gonic/gin"
	"github.com/swaggo/swag"
)

const scalarVersion = "1.76.4"

const scalarHTML = `<!doctype html>
<html>
  <head>
    <title>API Reference</title>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
  </head>
  <body>
    <script id="api-reference" data-url="/swagger/doc.json"></script>
    <script src="https://cdn.jsdelivr.net/npm/@scalar/api-reference@` + scalarVersion + `"></script>
  </body>
</html>`

// RegisterRoutes mounts the Scalar API reference UI and the OpenAPI spec
// generated by swag (see `make swag`).
//
//	GET /swagger/index.html -> Scalar UI
//	GET /swagger/doc.json   -> OpenAPI spec
func RegisterRoutes(r *gin.Engine) {
	ui := func(c *gin.Context) {
		c.Data(http.StatusOK, "text/html; charset=utf-8", []byte(scalarHTML))
	}

	r.GET("/swagger", func(c *gin.Context) {
		c.Redirect(http.StatusMovedPermanently, "/swagger/index.html")
	})
	r.GET("/swagger/index.html", ui)
	r.GET("/swagger/doc.json", func(c *gin.Context) {
		doc, err := swag.ReadDoc()
		if err != nil {
			c.String(http.StatusInternalServerError, err.Error())
			return
		}
		c.Data(http.StatusOK, "application/json; charset=utf-8", []byte(doc))
	})
}
